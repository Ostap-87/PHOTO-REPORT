# настоящее время (3 л. ед. ч.) неправильных глаголов -> инфинитив
PRES_IRR = {"передает": "передавать", "передаёт": "передавать", "создает": "создавать", "создаёт": "создавать",
            "сдает": "сдавать", "сдаёт": "сдавать", "выдает": "выдавать", "выдаёт": "выдавать",
            "ведет": "вести", "ведёт": "вести", "несет": "нести", "несёт": "нести", "моет": "мыть"}
GENDER = {"m": "", "f": "а", "n": "о", "p": "и"}
MODAL = {"должен": "m", "должна": "f", "должно": "n", "должны": "p", "обязан": "m", "обязана": "f",
         "обязано": "n", "обязаны": "p", "обязуется": "m", "обязуются": "p"}
BE_PAST = {"m": "был", "f": "была", "n": "было", "p": "были"}


def _present_forms() -> dict[str, str]:
    """Формы 3 л. ед. ч. глаголов словаря -> инфинитив (по правилам спряжения)."""
    out = dict(PRES_IRR)
    for inf in PERF:
        if inf.endswith(("авать",)) and not inf.endswith(("ывать", "ивать")):        # передавать
            out[inf[:-4] + "ет"] = inf
            out[inf[:-4] + "ёт"] = inf
        elif inf.endswith(("овать", "евать")):                                     # формировать
            out[inf[:-5] + "ует"] = inf
        elif inf.endswith(("ать", "ять")):                                         # обеспечивать, предоставлять
            out[inf[:-2] + "ет"] = inf
        elif inf.endswith("ить"):                                                  # проводить
            out[inf[:-3] + "ит"] = inf
    return out


PRESENT = _present_forms()


def past(inf: str, g: str = "m") -> str:
    """Прошедшее время инфинитива в роде/числе g (m, f, n, p)."""
    refl = inf.endswith(("ться", "тись"))
    base = inf[:-2] if refl else inf
    if base in PAST_IRR:
        m, stem = PAST_IRR[base]
        form = m if g == "m" else stem + GENDER[g]
    elif base.endswith("ть"):
        form = base[:-2] + "л" + GENDER[g]
    else:
        return inf
    if refl:
        form += "ся" if g == "m" else "сь"
    return form


def _perf_past(inf: str, g: str) -> str:
    return past(PERF.get(inf, inf), g)


def _is_verb(word: str) -> bool:
    """Инфинитив, а не существительное на «-ть» («часть», «мощность»)."""
    w = word.lower()
    if w in PERF or w in PERF.values():
        return True
    return bool(re.search(r"(овать|евать|ивать|ывать|ять|ать|ить|еть)(ся)?$", w)) and not re.search(r"сть(ся)?$", w)


def _keep_case(src: str, dst: str) -> str:
    return dst[:1].upper() + dst[1:] if src[:1].isupper() else dst


_WORD = r"[А-Яа-яЁё]+"
_SENT_SPLIT = re.compile(r"(?<=[^\d\s][.;!?])(\s+)|(\n)")


def _sentence(s: str) -> str:
    # 1) «должна быть …» -> «была …»
    s = re.sub(r"\b(должен|должна|должно|должны|обязан|обязана|обязаны)\s+быть\b",
               lambda m: _keep_case(m.group(1), BE_PAST[MODAL[m.group(1).lower()]]), s, flags=re.I)

    # 2) «должен / обязан / обязуется (не) обеспечить (и согласовать)» -> «обеспечил (и согласовал)»
    def modal(m: re.Match) -> str:
        g = MODAL[m.group(1).lower()]
        neg = m.group(2) or ""
        verbs = re.sub(_WORD, lambda w: _perf_past(w.group(0).lower(), g) if re.fullmatch(r"[а-яё]+(?:ть|ться|ти|чь)",
                                                                                         w.group(0).lower()) else w.group(0),
                       m.group(3))
        return _keep_case(m.group(1), neg + verbs) if not neg else _keep_case(m.group(1), neg) + verbs
    found = []

    def modal_g(m: re.Match) -> str:
        found.append(MODAL[m.group(1).lower()])
        return modal(m)
    s = re.sub(r"\b(должен|должна|должно|должны|обязан|обязана|обязаны|обязуется|обязуются)\s+(не\s+)?"
               r"((?:[а-яё]+(?:ть|ться|ти|чь))(?:\s*(?:,|и)\s*[а-яё]+(?:ть|ться|ти|чь))*)\b", modal_g, s, flags=re.I)
    if found:   # однородные дальше по предложению: «обеспечивать … и не передавать» -> «… и не передавал»
        g = found[-1]
        s = re.sub(r"(\b(?:и|а\s+также)\s+(?:не\s+)?|,\s+(?:не\s+)?)([а-яё]{2,}(?:ть|ться))\b",
                   lambda w: w.group(1) + (_perf_past(w.group(2), g) if _is_verb(w.group(2)) else w.group(2)), s)

    # 3) подлежащее «Исполнитель» — глаголы настоящего времени после него
    m = re.search(r"\bИсполнитель\b", s)
    if m:
        head, tail = s[:m.end()], s[m.end():]

        def pres(w: re.Match) -> str:
            word = w.group(0)
            inf = PRESENT.get(word.lower())
            return _keep_case(word, _perf_past(inf, "m")) if inf else word
        s = head + re.sub(_WORD, pres, tail)

    # 4) инфинитив в начале предложения: «Обеспечить наличие» -> «Обеспечили наличие»
    s = re.sub(r"^(\s*(?:[-–•]\s*)?)(" + _WORD + r")\b",
               lambda w: w.group(1) + (_keep_case(w.group(2), _perf_past(w.group(2).lower(), "p"))
                                       if w.group(2).lower() in PERF or w.group(2).lower() in {
                                           PERF[k] for k in PERF} else w.group(2)), s)
    return s


def perfect(text: str) -> str:
    """Весь текст пункта в совершенном виде (по предложениям и строкам)."""
    if not text:
        return text
    parts = _SENT_SPLIT.split(text)
    out = []
    for p in parts:
        if p is None:
            continue
        out.append(p if not p.strip() else _sentence(p))
    return "".join(out)
